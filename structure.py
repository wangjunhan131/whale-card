_SPLIT = re.compile(r"[，。！？；、\n]+")


def clauses(text):
    """按标点切子句，去掉空片与纯语气词。"""
    out = []
    for s in _SPLIT.split((text or "").strip()):
        s = s.strip()
        if s and s not in ("嗯", "啊", "哦", "对", "好", "是", "行", "嗯嗯", "哈哈", "嘿嘿"):
            out.append(s)
    return out


def extract_place(text):
    t = text or ""
    # 长词优先（「宠物医院」不该只认成「医院」）
    hit = ""
    for p in PLACES:
        if p in t and len(p) > len(hit):
            hit = p
    return hit


def extract_person(text):
    t = text or ""
    names = [p for p in PERSONS if p in t]
    if not names:
        return ""
    # 去重 + 保序（「妈妈妈妈」这种事常有）
    seen, out = set(), []
    for n in names:
        if n not in seen:
            seen.add(n)
            out.append(n)
    return ",".join(out[:3])


def extract_kind(text):
    t = text or ""
    for kind, words in KINDS:
        for w in words:
            if w in t:
                return kind
    return ""


def extract(text):
    """返回 (who, where, ev_kind)；抽不出来的留空字符串。"""
    return extract_person(text), extract_place(text), extract_kind(text)


