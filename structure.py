_NAME_RX = re.compile(r"([\u4e00-\u9fa5]{2,3}?)(?:说|问|讲|答|喊|笑|哭|回|又来|也来)")


def extract_person(text):
    s = text or ""
    got = []
    for p in PERSONS:
        if p and p in s and p not in got:
            got.append(p)
    if not got:
        for m in _NAME_RX.finditer(s):
            nm = m.group(1)
            if nm in _STOP_PERSON or nm in got:
                continue
            if s[max(0, m.start() - 1):m.start()] in ("他", "她", "我", "你", "也", "又"):
                continue
            got.append(nm)
            break
    return ",".join(got[:3])


